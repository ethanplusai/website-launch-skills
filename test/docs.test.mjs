// The documentation contract.
//
// Three things can quietly drift apart: what the checks actually are, what `docs/checks.md` says
// they are, and what the README promises a reader will find. The first pair is held together by
// regenerating the inventory into a string and comparing it byte-for-byte with the committed file
// — if a check is added, renamed or re-severitied and nobody ran `npm run gen:checks`, this fails.
// The rest is a floor, not a style guide: the README has to name all three skills, say read-only,
// say `Not covered`, say Node 20, and every `docs/*.md` file it links to has to exist.

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { REPO_ROOT } from './helpers.mjs'
import { renderChecksDoc } from '../scripts/gen-checks-doc.mjs'

const read = (rel) => readFileSync(join(REPO_ROOT, rel), 'utf8')

test('docs/checks.md is exactly what the generator renders', () => {
  assert.equal(read('docs/checks.md'), renderChecksDoc())
})

test('docs/checks.md says it is generated and names the generator', () => {
  const doc = read('docs/checks.md')
  assert.match(doc, /Generated by scripts\/gen-checks-doc\.mjs — do not edit by hand/)
})

test('the README says the things a first-time reader needs', () => {
  const readme = read('README.md')
  for (const needle of ['pre-launch', 'launch-audit', 'post-launch', 'read-only', 'Not covered', 'Node 20']) {
    assert.ok(readme.includes(needle), `README.md does not mention "${needle}"`)
  }
})

test('every docs file the README links to exists', () => {
  const readme = read('README.md')
  const links = [...readme.matchAll(/\]\((?:\.\/)?(docs\/[A-Za-z0-9._/-]+\.md)\)/g)].map((m) => m[1])
  assert.ok(links.length >= 2, 'the README should link at least the check inventory and the sources')
  for (const link of links) {
    assert.ok(existsSync(join(REPO_ROOT, link)), `README.md links ${link}, which does not exist`)
  }
})

test('AGENTS.md names all three skills', () => {
  const agents = read('AGENTS.md')
  for (const name of ['pre-launch', 'launch-audit', 'post-launch']) {
    assert.ok(agents.includes(name), `AGENTS.md does not mention "${name}"`)
  }
})

test('the marketplace manifest parses and lists exactly the three skills', () => {
  const manifest = JSON.parse(read('.claude-plugin/marketplace.json'))
  assert.equal(manifest.name, 'website-launch-skill')
  assert.equal(manifest.plugins.length, 1)
  const skills = manifest.plugins[0].skills
  assert.deepEqual(skills, ['./skills/pre-launch', './skills/launch-audit', './skills/post-launch'])
  for (const skill of skills) {
    assert.ok(existsSync(join(REPO_ROOT, skill, 'SKILL.md')), `${skill} has no SKILL.md`)
  }
})
