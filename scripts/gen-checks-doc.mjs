#!/usr/bin/env node
// Renders `docs/checks.md` from the code that actually runs.
//
// This is a development tool, not part of any skill. It lives at the repository root precisely so
// that nothing a skill ships depends on it: a user who copies `skills/*` gets the checks, and this
// file stays behind with the tests.
//
// The point of generating the inventory rather than writing it is that a hand-written one is wrong
// the first time somebody renames a check, and nobody notices for a release. Here the document is
// a function of the three registries, `test/docs.test.mjs` compares the function's output with the
// committed file byte-for-byte, and `--check` does the same from CI or a hook. A check that is
// added, renamed, re-severitied or moved to another tier turns the suite red until the doc is
// regenerated.
//
// Determinism is the whole contract: no timestamp, no counts of anything that varies by machine,
// no ordering that depends on filesystem order. Phases come out in the order a launch runs them,
// dimensions in each registry's own insertion order (which is the order a person should read them
// in), and ids sorted inside a dimension so a diff of this file is readable.
//
//   node scripts/gen-checks-doc.mjs           write docs/checks.md
//   node scripts/gen-checks-doc.mjs --check   exit 1 if the committed file is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { buildRegistry as auditRegistry } from '../skills/launch-audit/scripts/launch-audit.mjs'
import { buildRegistry as gateRegistry } from '../skills/pre-launch/scripts/lib/gate.mjs'
import { cutoverRegistry } from '../skills/post-launch/scripts/lib/cutover.mjs'

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const DOC_PATH = join(REPO_ROOT, 'docs', 'checks.md')

const GENERATED_BY = 'Generated by scripts/gen-checks-doc.mjs — do not edit by hand'

// Launch order, which is also dependency order: the gate before the deploy, the audit against what
// was deployed, the watch after DNS moves.
const PHASES = [
  {
    phase: 'pre-launch',
    heading: 'pre-launch — the gate',
    blurb: 'Runs against the repository and its build output before a deploy. Any `fail` exits 1 and blocks the launch; no flag softens one.',
    registry: gateRegistry,
  },
  {
    phase: 'launch-audit',
    heading: 'launch-audit — the auditor',
    blurb: 'Crawls a staging or live url and reports. It always exits 0 — it reports, it does not gate.',
    registry: auditRegistry,
  },
  {
    phase: 'post-launch',
    heading: 'post-launch — the watch',
    blurb: 'Runs the moment DNS has moved and once a day for thirty days after. It always exits 0.',
    registry: cutoverRegistry,
  },
]

// A markdown table cell cannot carry a raw pipe or newline. No check text has either today; the
// escape is here so that the day one does, the document stays a table instead of becoming rubble.
const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim()

// Every check in the repository, in document order: phase by phase, dimension by dimension in the
// registry's own order, and id-sorted inside a dimension.
export function allChecks() {
  return PHASES.flatMap(({ registry }) => registry().list())
}

// Groups a phase's checks by dimension, keeping the order the registry registered them in, and
// sorting the rows inside each group.
function byDimension(checks) {
  const groups = new Map()
  for (const check of checks) {
    if (!groups.has(check.dimension)) groups.set(check.dimension, [])
    groups.get(check.dimension).push(check)
  }
  for (const rows of groups.values()) rows.sort((a, b) => a.id.localeCompare(b.id))
  return groups
}

export function renderChecksDoc() {
  const phases = PHASES.map((definition) => ({ ...definition, checks: definition.registry().list() }))
  const total = phases.reduce((sum, p) => sum + p.checks.length, 0)

  const lines = [
    '# Check inventory',
    '',
    `*${GENERATED_BY}.* Run \`npm run gen:checks\` after adding, renaming or re-severitying a check;`,
    '`test/docs.test.mjs` fails while this file and the registry disagree.',
    '',
    `**${total} checks** — ${phases.map((p) => `${p.checks.length} in \`${p.phase}\``).join(', ')}.`,
    '',
    'Severity is what a finding costs: `blocker` stops a launch, `high` is losing something today,',
    '`medium` and `low` are worth fixing, `info` reports a state rather than a fault. Tier is what a',
    'check needs in order to run: `repo` reads files on disk, `http` makes requests, `browser` needs',
    'the optional Playwright tier, `human` is a question only a person can answer.',
    '',
  ]

  for (const { heading, blurb, checks } of phases) {
    lines.push(`## ${heading}`, '', blurb, '')
    for (const [dimension, rows] of byDimension(checks)) {
      lines.push(`### ${dimension} (${rows.length})`, '')
      lines.push('| id | severity | tier | title | catches |')
      lines.push('|---|---|---|---|---|')
      for (const check of rows) {
        lines.push(`| \`${check.id}\` | ${check.severity} | ${check.tier} | ${cell(check.title)} | ${cell(check.catches)} |`)
      }
      lines.push('')
    }
  }

  return `${lines.join('\n').replace(/\n+$/, '')}\n`
}

function main(argv) {
  const rendered = renderChecksDoc()
  if (argv.includes('--check')) {
    let committed = null
    try {
      committed = readFileSync(DOC_PATH, 'utf8')
    } catch {
      process.stderr.write(`docs/checks.md is missing. Run: npm run gen:checks\n`)
      return 1
    }
    if (committed !== rendered) {
      process.stderr.write('docs/checks.md is stale — it no longer matches the check registry. Run: npm run gen:checks\n')
      return 1
    }
    process.stdout.write('docs/checks.md is up to date.\n')
    return 0
  }
  writeFileSync(DOC_PATH, rendered)
  process.stdout.write(`Wrote docs/checks.md — ${allChecks().length} checks.\n`)
  return 0
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main(process.argv.slice(2)))
}
